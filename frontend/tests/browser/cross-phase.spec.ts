import { openAnalytics } from "./review-capture";
import { expect, test } from "@playwright/test";
import { captureWorkspace } from "./review-capture";

const backend = "http://127.0.0.1:8100";

test("edited saved facts stay canonical and old analysis remains a labelled snapshot", async ({ page, request }, info) => {
  const created = await request.post(`${backend}/api/jobs`, { data: { company: `Provenance ${info.project.name} ${Date.now()}`, role_title: "Engineer", summary: "Original saved summary", responsibilities: ["Original saved duty"], required_skills: ["Python"], source_content: "Original full posting preserved for tailoring.", links: [{ kind: "source", label: "Saved posting", url: "https://example.test/original-posting" }] } });
  expect(created.ok()).toBeTruthy();
  const job = await created.json();
  const generated = await request.post(`${backend}/api/ai/run-advanced-analysis/${job.id}`);
  expect(generated.ok()).toBeTruthy();
  const analysis = (await generated.json()).analysis;
  const fields = { summary: "Corrected saved job summary", responsibilities: ["Maintain the corrected system"], required_skills: ["Rust", "Stakeholder communication"], pay_min: 150000, pay_max: 165000, pay_period: "year", pay_currency: "USD", pay_raw: null };
  expect((await request.patch(`${backend}/api/jobs/${job.id}`, { data: fields })).ok()).toBeTruthy();
  let analysisWrites = 0;
  page.on("request", req => { if (req.method() === "POST" && req.url().includes("run-advanced-analysis")) analysisWrites++; });
  await page.goto(`/jobs/${job.id}`);
  const facts = page.locator("section").filter({ has: page.locator("#role-snapshot") }).last();
  const snapshot = page.locator("section").filter({ has: page.locator("#analysis-snapshot") }).last();
  await expect(facts.getByText(fields.summary, { exact: true })).toBeVisible();
  await expect(facts.getByText(fields.responsibilities[0], { exact: true })).toBeVisible();
  await expect(facts.getByText("Stakeholder communication", { exact: true })).toBeVisible();
  await expect(facts.getByText(analysis.job_insights.summary, { exact: true })).toHaveCount(0);
  await expect(snapshot.getByRole("status")).toContainText("may be outdated");
  await expect(page.getByText("Pay", { exact: true })).toHaveCount(1);
  await expect(page.getByText("USD 150,000-165,000 / year", { exact: true })).toHaveCount(1);
  await snapshot.locator("summary", { hasText: "Analysis interpretation of the role" }).click();
  await expect(snapshot.getByText(analysis.job_insights.summary, { exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Saved posting", exact: true }).last()).toHaveAttribute("href", "https://example.test/original-posting");
  await page.getByRole("button", { name: "Edit job", exact: true }).click();
  await expect(page.getByLabel("Summary", { exact: true })).toHaveValue(fields.summary);
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.reload();
  await expect(facts.getByText(fields.summary, { exact: true })).toBeVisible();
  const after = await (await request.get(`${backend}/api/ai/advanced-analysis/${job.id}`)).json();
  expect(after.analysis).toEqual(analysis);
  expect(analysisWrites).toBe(0);
  expect((await (await request.get(`${backend}/api/jobs/${job.id}`)).json()).source_content).toBe("Original full posting preserved for tailoring.");
  await captureWorkspace(page, info, "job-provenance.png");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBeTruthy();
});

test("shared analytics dates, legacy aliases, group filters and back/forward agree", async ({ page, request }) => {
  await page.goto("/reports?saved_since=2099-01-01&dimension=category&audit=keep");
  await openAnalytics(page);
  const date = page.getByLabel("Jobs saved on or after (UTC)", { exact: true });
  const views = page.getByRole("navigation", { name: "Dashboard views" });
  await expect(date).toHaveValue("2099-01-01");
  await expect(page.getByLabel("Group by", { exact: true })).toHaveValue("category");
  await expect(page.getByRole("heading", { name: "0 saved jobs in this cohort", exact: true })).toBeVisible();
  await date.fill("2000-01-01");
  await expect(page).toHaveURL(/since=2000-01-01/);
  expect(new URL(page.url()).searchParams.has("saved_since")).toBe(false);
  const outcomes = await (await request.get(`${backend}/api/reports/outcomes?saved_since=2000-01-01`)).json();
  await expect(page.getByRole("heading", { name: `${outcomes.total_jobs} saved jobs in this cohort`, exact: true })).toBeVisible();
  await views.getByRole("button", { name: "Overview", exact: true }).click();
  await expect(date).toHaveValue("2000-01-01");
  await expect(page.getByRole("link", { name: "View funnel jobs", exact: true })).toHaveAttribute("href", "/jobs?funnel=Saved&since=2000-01-01");
  await page.reload();
  await expect(date).toHaveValue("2000-01-01");
  await page.goBack();
  await expect(views.getByRole("button", { name: "Outcomes", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.goBack();
  await expect(date).toHaveValue("2099-01-01");
  await page.goForward();
  await expect(date).toHaveValue("2000-01-01");
  expect(new URL(page.url()).searchParams.get("audit")).toBe("keep");
  await page.goto("/dashboard?tab=outcomes&since=2000-01-01&outcomesSince=2099-01-01");
  await expect(date).toHaveValue("2000-01-01");
  await expect(page.getByRole("status").filter({ hasText: "different legacy date filters" })).toBeVisible();
  await openAnalytics(page);
  await page.getByRole("button", { name: "All time", exact: true }).click();
  expect(new URL(page.url()).searchParams.has("outcomesSince")).toBe(false);
  expect(new URL(page.url()).searchParams.has("since")).toBe(false);
  await page.goto("/dashboard?tab=outcomes&outcomesSince=2099-01-01");
  await expect(date).toHaveValue("2099-01-01");
});

test("invalid analytics dates are announced on the field and recover without an all-time fallback", async ({ page }) => {
  await page.goto("/dashboard?since=2026-02-30");
  await openAnalytics(page);
  const date = page.getByLabel("Jobs saved on or after (UTC)", { exact: true });
  await expect(page.getByRole("alert").filter({ hasText: "Invalid date in this link" })).toBeVisible();
  await expect(date).toHaveAttribute("aria-invalid", "true");
  await openAnalytics(page);
  await page.getByRole("button", { name: "All time", exact: true }).click();
  await expect(date).toHaveAttribute("aria-invalid", "false");
  await expect(page.getByRole("heading", { name: "Application Sankey", exact: true })).toBeVisible();
  await page.goto("/dashboard?since=&outcomesSince=2099-01-01&tab=outcomes");
  await expect(date).toHaveValue("");
  await expect(page.getByRole("heading", { name: "0 saved jobs in this cohort", exact: true })).toHaveCount(0);
});

test("browser navigation closes a hidden view's modal and keeps the selected learning focus", async ({ page, request }) => {
  await page.goto("/dashboard?tab=overview");
  const views = page.getByRole("navigation", { name: "Dashboard views" });
  await views.getByRole("button", { name: "Skills & learning", exact: true }).click();
  await page.getByRole("button", { name: "Choose skills", exact: true }).click();
  const gaps = await (await request.get(`${backend}/api/skill-gaps`)).json();
  const gap = gaps.find((item: { user_level: string }) => item.user_level !== "high");
  await page.getByRole("checkbox", { name: `Focus on ${gap.skill_name}`, exact: true }).check();
  await page.getByRole("button", { name: `View evidence for ${gap.skill_name}`, exact: true }).click();
  await expect(page.getByRole("dialog", { name: `Evidence for ${gap.skill_name}`, exact: true })).toBeVisible();
  await page.goBack();
  await expect(views.getByRole("button", { name: "Overview", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe("hidden");
  await page.goForward();
  await expect(page.getByRole("checkbox", { name: `Focus on ${gap.skill_name}`, exact: true })).toBeChecked();
});
